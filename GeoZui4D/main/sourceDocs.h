/**
\page georef Georeferencing
Every object in GZ has a location in space. GZ's internal unit
for specifying a point in 3D space is the meter and expects points
to be projected in UTM. ProjectionSpec can be used to project to UTM or 
an object may call its Object::projectXY member funtion.
\section refFrames Frames of Reference
Objects are typically defined by multiple points. A Gutm for example is a grid 
of hundreds or thousands of points. To save memory and to  make itself easily
movable, an Object is a PosableStateUser and thus contains a pose (PosableStateBase).<br><br>
The pose contains the object's position in the real world and can be used as its local
reference point. When an object is rendered, the scene will be centered around the
object's pose. The object just needs to render its parts using coordinates relative
to this local point.<br><br>
The OpenGL x,y,z coordinates map to easting,northing,up.
\section fvsd floats vs double
In order to avoid inaccuracies in positions while rendering, we have to
avoid calling such commands as glTranslatef with large values. UTM coordinates
tend to be quite large, in the order of hundred's of thounsands. Although 
doubles could safely handle such values and glTranslated be used, there is
no garantee that graphics hardware and/or drivers will preserve the precision.<br><br>
Part of this problem is solved by rendering objects using their local coordinate systems.
GZ used to have a global reference point from which all objects where positioned. 
The object's pose would contain a small offset (as compared to an absolute UTM coordinate) 
from the glabel (scene) georef point. The global ref was OpenGL's 0,0,0, and glTranslatef's
would move to each object. This normally (but not always!) solved the accuracy
problem while rendering. It could sometimes happen that global reference point would be
set a wrong position, creating large offsets for the object's poses, introducing 
jittering objects while the scene was changing. Two levels of references also added
a layer of complexity with more exotic objects, such as MissionPlan, that have moving
parts, and that can also be moved. Comparing points from different objects also 
was more comlicated than needed.<br><br>
The global reference point was eliminated to reduce this complexity. Now, an Object's
pose describes its global position. To prevent large values while moving to an object's
local reference point, OpenGL's 0,0,0 is set to the center of workspace, and the 
object's pose only needs to translate from this point. Large translations only occur
for objects that far from the center of workspace, so if the are far enough to be
 inaccurate, they should also be far enough for the viewer not to notice.
*/
