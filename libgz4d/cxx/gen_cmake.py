def genBoostPython(path):
    sources = []
    raw_sources = glob.glob(os.path.join(path,'*.cpp'))
    for s in raw_sources:
        sources.append(os.path.basename(s))

    pysources = []
    for s in glob.glob(os.path.join(path,'*.py')):
        pysources.append(os.path.basename(s))

    sub_modules = []
    for sm in glob.glob(os.path.join(path,'*')):
        if os.path.isdir(sm):
            sub_modules.append(os.path.basename(sm))
    sub_modules.sort()

    if len(sources) or len(pysources) or len(sub_modules):
        cmake = FileUpdater(os.path.join(path,'CMakeLists.txt'))
        cmake.write('# auto generated by gen_cmake.py\n\n')

        if os.path.sep in path: 
            install_path = '/'.join(['lib/python2.7/dist-packages/gz4d']+path.split(os.path.sep,1)[1:])
            gzlib = 'gz4d_'+'_'.join(path.split(os.path.sep,1)[1].split(os.path.sep))
        else:
            install_path = 'lib/python2.7/dist-packages/gz4d'
            gzlib = ''


            

        all_deps = deps.findDepsInFiles(raw_sources)
        ext_deps = []
        gz_deps = []
        for d in all_deps:
            if d.startswith('gz4d'):
                gz_deps.append(d)
            else:
                ext_deps.append(d+'_FOUND')
        
        tab = ''
        if len(ext_deps):
            tab = '  '
            cmake.write('if('+' AND '.join(ext_deps)+')\n')

        for s in sources:
            
                
            
            target = '_'.join(path.split(os.path.sep))+'_'+s
            cmake.write(tab+'add_library('+target+' SHARED '+s+')\n')
            cmake.write(tab+'target_link_libraries('+target+' '+(' '.join(gz_deps))+' ${LIBS})\n')
            cmake.write(tab+'set_target_properties('+target+' PROPERTIES OUTPUT_NAME '+os.path.splitext(s)[0]+')\n')
            cmake.write(tab+'set_target_properties('+target+' PROPERTIES PREFIX "")\n')
            cmake.write(tab+'set_target_properties('+target+' PROPERTIES INSTALL_RPATH "$ORIGIN/'+'../'*(len(install_path.split('/'))-1)+'")\n')
            cmake.write(tab+'install(TARGETS '+target+' LIBRARY DESTINATION '+install_path+' RUNTIME DESTINATION '+install_path+')\n')
            cmake.write('\n')

                    
            
        if len(pysources):
            cmake.write(tab+'install(FILES '+' '.join(pysources)+' DESTINATION '+install_path+')\n')

        for sub_path in sub_modules:
            if genBoostPython('/'.join((path,sub_path))):
                cmake.write(tab+'add_subdirectory('+sub_path+')\n')

        if len(ext_deps):
            cmake.write('else()\n')
            cmake.write(tab+'message("skipping boost package '+path.rsplit(os.path.sep,1)[1]+'")\n')
            for d in ext_deps:
                cmake.write(tab+'  message("    '+d+' ${'+d+'}")\n')
            cmake.write('endif()\n')

        return True

    return False

genBoostPython('boost.python')
