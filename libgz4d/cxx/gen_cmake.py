import os
import glob
import gz4d_deps


deps = gz4d_deps.Headers()

class FileUpdater:
    def __init__(self,path):
        self.path = path
        self.content = ''

    def __del__(self):
        if os.path.exists(self.path) and file(self.path).read() == self.content:
            return
        file(self.path,'w').write(self.content)

    def write(self,s):
        self.content += s


def genModules(path,mod_name,modules):
    sources = []
    raw_sources = glob.glob(os.path.join(path,'*.cpp')) + glob.glob(os.path.join(path,'*.c'))
    for s in raw_sources:
        sources.append(os.path.basename(s))

    sub_modules = []
    for sm in glob.glob(os.path.join(path,'*')):
        if os.path.isdir(sm):
            sub_modules.append(sm)
    sub_modules.sort()

    if len(sources) or len(sub_modules):
        cmake = FileUpdater(os.path.join(path,'CMakeLists.txt'))
        cmake.write('# auto generated by gen_cmake.py\n\n')


        if len(sources):
            src_var = mod_name.upper()+'_LIB_SRC'

            cmake.write('include(local.cmake OPTIONAL)\n')
            tab = ''

            all_deps = deps.findDepsInFiles(raw_sources)
            ext_deps = []
            for d in all_deps:
                if not d.startswith('gz4d'):
                    ext_deps.append(d+'_FOUND')
            
            if len(ext_deps):
                cmake.write(tab+'if('+' AND '.join(ext_deps)+')\n')
                tab += '  '

            cmake.write(tab+'set('+src_var+' '+' '.join(sources)+')\n')
            cmake.write(tab+'add_library('+mod_name+' ${LIB_TYPE} ${'+src_var+'})\n')

            cmake.write(tab+'if(BUILD_SHARED_LIBS)\n')
            cmake.write(tab+'  target_link_libraries('+mod_name+' ${LIBS})\n')
            cmake.write(tab+'endif(BUILD_SHARED_LIBS)\n')
            
            cmake.write(tab+'install(TARGETS '+mod_name+' LIBRARY DESTINATION lib RUNTIME DESTINATION bin ARCHIVE DESTINATION lib)\n')
            if len(ext_deps):
                tab = tab[0:-2]
                cmake.write(tab+'else()\n')
                cmake.write(tab+'  message("skipping '+mod_name+'")\n')
                for d in ext_deps:
                    cmake.write(tab+'  message("    '+d+' ${'+d+'}")\n')
                cmake.write(tab+'endif()\n')



            modules.append(mod_name)
            

        for sub_path in sub_modules:
            sub_module = os.path.split(sub_path)[1]

            if sub_module == 'gz4d':
                sub_mod_name = mod_name
            else:
                sub_mod_name = '_'.join((mod_name,sub_module))
                
            if genModules(sub_path,sub_mod_name,modules):
                cmake.write('add_subdirectory('+sub_module+')\n')

        #cmake.write('set(LIBS ${LIBS} PARENT_SCOPE)\n')
        return True
    return False
    

modules = []

genModules('src','gz4d',modules)


